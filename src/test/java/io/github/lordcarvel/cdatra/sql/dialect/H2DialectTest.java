package io.github.lordcarvel.cdatra.sql.dialect;

import io.github.lordcarvel.cdatra.sql.SqlType;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.EnumSource;

import static org.junit.jupiter.api.Assertions.*;

class H2DialectTest {

    private final H2Dialect dialect = new H2Dialect();

    @ParameterizedTest
    @EnumSource(SqlType.class)
    void usesTheSqlTypeNameAsColumnType (SqlType type) {

        assertEquals(type.name(), dialect.typeName(type));
    }

    @Test
    void writesIdentityColumnsWithTheirOwnType () {

        assertEquals("id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", dialect.generatedIdColumn("id", SqlType.INTEGER));
        assertEquals("id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", dialect.generatedIdColumn("id", SqlType.BIGINT));
    }

    @Test
    void rejectsNullType () {

        assertThrows(IllegalArgumentException.class, () -> dialect.typeName(null));
        assertThrows(IllegalArgumentException.class, () -> dialect.generatedIdColumn("id", null));
    }
}
